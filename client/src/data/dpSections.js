//      Best Time to Buy and Sell Stock I..IV, House Robber I..III,
//      Palindrome Partitioning II..IV, Coin Change 1..2, Cherry Pickup I..II.
//   4. A family member lives in the sheet its *technique* belongs to, not the
//      one its name suggests. Stone Game VI and IX are greedy/counting, so they
//      sit in the greedy sheet. Jump Game I/II are greedy, III/IV are BFS and
